#!/usr/bin/env bash
# Refresh the vendored Claude skills under claude/skills/ from their GitHub sources and rewrite the pins.
# Usage: bash claude/sync-skills.sh   (needs git + gh auth for the private repos)
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DST="$HERE/skills"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

# repo | skill dir inside repo (. = repo root) | skill names | root-level paths copied when dir is "."
clone() { git clone -q --depth 1 "git@github.com:zaytsevand/$1.git" "$WORK/$1"; git -C "$WORK/$1" rev-parse --short HEAD; }

rm -rf "$DST"; mkdir -p "$DST"
{
  echo "# Vendored skills"; echo
  echo "Generated by \`claude/sync-skills.sh\`; do not hand-edit the skill folders."; echo
  echo "| Skill | Source | Commit |"; echo "|---|---|---|"
} > "$HERE/VENDORED.md"

pin=$(clone chorus)
for s in chorus-core chorus-learn chorus-review chorus-sdlc; do
  cp -R "$WORK/chorus/skill/$s" "$DST/$s"; echo "| $s | zaytsevand/chorus | \`$pin\` |" >> "$HERE/VENDORED.md"
done

# Standalone skills: the skill is the repo root, minus repo-only files.
for spec in "coryphaeus:SKILL.md README.md LICENSE schema bin examples" "problem-brief:SKILL.md reference bin schema examples plugin"; do
  name=${spec%%:*}; items=${spec#*:}; pin=$(clone "$name"); mkdir -p "$DST/$name"
  for i in $items; do [ -e "$WORK/$name/$i" ] && cp -R "$WORK/$name/$i" "$DST/$name/"; done
  echo "| $name | zaytsevand/$name | \`$pin\` |" >> "$HERE/VENDORED.md"
done
echo "synced; pins in claude/VENDORED.md"
